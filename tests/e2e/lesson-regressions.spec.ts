import { test, expect, type Page } from '@playwright/test'

const next = (page: Page) => page.locator('.lesson-nav').getByRole('button', { name: '다음', exact: true })
const previous = (page: Page) => page.locator('.lesson-nav').getByRole('button', { name: '이전', exact: true })
const step = (page: Page, n: number) => page.locator('.stepbar button').nth(n - 1).click()

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('ee.settings.v1', JSON.stringify({ preferredMapMode: '2d', soundEnabled: false, lowPower: true, landingMotion: false })))
  await page.goto('/explore')
  await expect(page.locator('.stepbar button')).toHaveCount(8, { timeout: 60000 })
})

test('설명과 한계: 저장 전 이동·별도 저장·새로 시작', async ({ page }) => {
  await step(page, 8)
  await page.locator('#exp-text').fill('작성 중인 설명')
  await next(page).click()
  await page.locator('#exp-lim').fill('작성 중인 한계')
  await previous(page).click()
  await expect(page.locator('#exp-text')).toHaveValue('작성 중인 설명')
  await page.getByRole('button', { name: '설명 저장', exact: true }).click()
  await next(page).click()
  await expect(page.locator('#exp-lim')).toHaveValue('작성 중인 한계')
  await next(page).click()
  await previous(page).click()
  await expect(page.locator('#exp-lim')).toHaveValue('작성 중인 한계')
  await page.getByRole('button', { name: '한계 저장', exact: true }).click()
  await previous(page).click()
  await page.locator('#exp-text').fill('')
  await next(page).click()
  await previous(page).click()
  await expect(page.locator('#exp-text')).toHaveValue('')
  await page.goto('/explore')
  await page.getByRole('button', { name: '새로 시작', exact: true }).click()
  await step(page, 8)
  await expect(page.locator('#exp-text')).toHaveValue('')
  await next(page).click()
  await expect(page.locator('#exp-lim')).toHaveValue('')
})

test('설명 건너뛰기는 다음 필수 활동에서 멈춘다', async ({ page }) => {
  await step(page, 4)
  await page.getByRole('button', { name: '설명 건너뛰기' }).click()
  await expect(page.getByRole('heading', { name: '최초 추론 그리기', exact: true })).toBeVisible()
  await expect(next(page)).toBeDisabled()
  await step(page, 6)
  await page.getByRole('button', { name: '설명 건너뛰기' }).click()
  await expect(page.getByRole('heading', { name: '화산 증거 열기', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '지도에서 확인하기' }).click()
  await next(page).click()
  await expect(page.locator('.task-steps')).toHaveText(/• 겹치는 곳 1곳 증거 담기• 겹치지 않는 곳 1곳 찾기/)
  await next(page).click()
  await page.getByRole('button', { name: '설명 건너뛰기' }).click()
  await expect(page.getByRole('heading', { name: '수정 추론 그리기', exact: true })).toBeVisible()
  await expect(next(page)).toBeDisabled()
})

test('완료 표시는 실제 기록만 사용하고 제출한 최초 선은 편집할 수 없다', async ({ page }, testInfo) => {
  await step(page, 3)
  await next(page).click()
  await next(page).click()
  await expect(page.locator('.task-steps')).toContainText('• 세 지역을 둘러보기')
  await expect(page.locator('.task-steps')).toContainText('○ 관찰 증거 1개 이상 담기')
  await page.getByRole('button', { name: '증거 서랍 열기/닫기' }).click()
  await page.getByRole('button', { name: '지금 화면 담기', exact: true }).click()
  await expect(page.locator('.task-steps')).toContainText('✓ 관찰 증거 1개 이상 담기')
  await page.getByRole('button', { name: '증거 서랍 열기/닫기' }).click()
  await step(page, 4)
  await next(page).click()
  const canvas = page.locator('.activity-stage canvas').first()
  const draw = async () => {
    await canvas.scrollIntoViewIfNeeded()
    const b = (await canvas.boundingBox())!
    await page.mouse.move(b.x + b.width * .42, b.y + b.height * .3)
    await page.mouse.down()
    for (let i = 1; i <= 10; i++) await page.mouse.move(b.x + b.width * .42 + i * 3, b.y + b.height * .3 + i * 5)
    await page.mouse.up()
  }
  await expect(page.locator('.task-steps')).toContainText('○ 최초 추론 제출')
  await draw()
  await page.getByRole('button', { name: '최초 추론 제출', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '제출', exact: true }).click()
  await expect(page.locator('.task-steps')).toContainText('✓ 최초 추론 제출')
  await expect(page.getByRole('button', { name: '그리기', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '최초 추론 제출', exact: true })).toHaveCount(0)
  await draw() // 제출 후 지도 조작은 이동만 한다.
  await expect(page.getByText(/최초 추론 제출 완료 · 선 1개/)).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('first-submitted.png'), fullPage: true })
  await step(page, 6)
  // 최초 선을 바탕으로 수정하는 기존 활동은 유지한다.
  for (let i = 0; i < 4; i++) {
    await next(page).click()
    if (i === 0) await page.getByRole('button', { name: '지도에서 확인하기' }).click()
  }
  await expect(page.getByText('그린 선 1/12')).toBeVisible()
  await draw()
  await expect(page.getByText('그린 선 2/12')).toBeVisible()
  await step(page, 4)
  await next(page).click()
  await expect(page.getByText(/최초 추론 제출 완료 · 선 1개/)).toBeVisible()
  await expect(page.getByRole('button', { name: '전체 지우기', exact: true })).toHaveCount(0)
})
