import { test, expect, type Browser, type Page } from '@playwright/test'
async function newPage(browser: Browser, viewport = { width: 1440, height: 1000 }) {
  const context = await browser.newContext({ viewport, locale: 'ko-KR' })
  const page = await context.newPage()
  await page.addInitScript(() => localStorage.setItem('ee.settings.v1', JSON.stringify({ soundEnabled: false, preferredMapMode: '2d', lowPower: true, landingMotion: false })))
  return page
}
async function drawLine(page: Page) {
  await page.getByRole('button', { name: '선 그리기', exact: true }).click()
  const canvas = page.locator('.simple-map-area canvas').first()
  await expect(canvas).toBeVisible()
  await canvas.scrollIntoViewIfNeeded()
  const b = (await canvas.boundingBox())!
  const x = b.x + b.width * .53, y = b.y + b.height * .35
  await page.mouse.move(x,y); await page.mouse.down()
  for (let i=1;i<=10;i++) await page.mouse.move(x+i*3,y+i*5)
  await page.mouse.up()
  await expect(page.getByText('그린 선 1개', { exact: true })).toBeVisible()
}
async function firstSubmit(page: Page) {
  await page.getByRole('button', { name: '첫 생각 제출하기', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: '이 선으로 제출', exact: true }).click()
  await expect(page.locator('.submitted')).toContainText('첫 생각')
}
async function advance(page: Page, name: string) {
  await page.locator('.lesson-nav').getByRole('button', { name, exact: true }).click()
}
